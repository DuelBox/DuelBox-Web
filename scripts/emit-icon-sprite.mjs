#!/usr/bin/env node
/**
 * Emits the interface-icon sprite (#74).
 *
 * Mirrors the tile sprite's same-document pattern: every glyph goes into the document once
 * as a `<symbol>`, and each use of it is a `<use href="#db-icon-…">` rather than another
 * copy of the path. The difference is only *when* — the tiles are emitted per page at
 * render by `TileSprite.tsx`, the icons once for the whole app at build time by this script,
 * because the icon set is small and fixed and belongs in every page's shell rather than
 * varying with the page.
 *
 * It reads the geometry from `apps/web/src/lib/icon-art.mjs` — the one source the typed
 * `icons.ts` reads too — and writes `apps/web/src/components/icon-sprite.generated.ts`, a
 * module exporting the sprite markup as a string. `IconSprite.tsx` drops that string into a
 * single hidden `<svg>`. The generated file is committed, and `icon-sprite.test.ts` fails if
 * it ever stops matching what this script would write, so a hand-edit or a geometry change
 * without a re-run is caught rather than shipped.
 *
 * Run: `node scripts/emit-icon-sprite.mjs` (or `pnpm emit:icons`).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ICON_NAMES, ICON_VIEWBOX, spriteSymbols } from '../apps/web/src/lib/icon-art.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'apps', 'web', 'src', 'components', 'icon-sprite.generated.ts');

/** The markup string: the `<symbol>`s only, so `IconSprite` owns the wrapping `<svg>`. */
export function spriteMarkup() {
  return spriteSymbols();
}

/** The full text of the generated module. */
export function generatedModule() {
  const symbols = spriteMarkup();
  return `/**
 * GENERATED by scripts/emit-icon-sprite.mjs — do not edit by hand.
 *
 * The interface glyphs as same-document <symbol>s (#74). Re-run \`pnpm emit:icons\` after
 * changing icon-art.mjs; \`icon-sprite.test.ts\` fails if this drifts from the emitter.
 */

/** The ${String(ICON_NAMES.length)} glyphs, viewBox 0 0 ${String(ICON_VIEWBOX)} ${String(ICON_VIEWBOX)}, drawn in currentColor. */
export const ICON_SPRITE = ${JSON.stringify(symbols)};
`;
}

function main() {
  const next = generatedModule();
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    current = '';
  }
  if (current === next) {
    process.stdout.write(`icon sprite already up to date (${String(ICON_NAMES.length)} glyphs)\n`);
    return;
  }
  writeFileSync(out, next);
  process.stdout.write(`wrote ${out} (${String(ICON_NAMES.length)} glyphs)\n`);
}

// Only write when run directly, so the test can import `generatedModule` without a side effect.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
