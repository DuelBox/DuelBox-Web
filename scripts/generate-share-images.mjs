#!/usr/bin/env node
/**
 * Compose every share image, at build time, once (#2453, #197).
 *
 * ## The rule this exists to keep
 *
 * "Generate share images and previews at build time, never on request." The site is
 * `output: 'export'` — a directory of files with no server runtime — so an on-demand image
 * route is not merely discouraged here, it is unimplementable: there is nothing running to
 * answer the request. Next's `ImageResponse` is the same story wearing a helpful face.
 * ADR 0001 prices the alternative: the whole cost model is that the origin serves files and
 * never computes, and a per-request image is the first line item on the other side of it.
 *
 * So this runs before `next build`, writes a PNG per game into `apps/web/public/og/`, and
 * the export copies them out like any other static file. A crawler fetching one costs
 * exactly what fetching a stylesheet costs.
 *
 * ## Why it can read TypeScript
 *
 * The artwork has one home — `apps/web/src/lib/tiles.ts` — and the pixels have to come from
 * there or the share image stops being the same picture as the tile. Other scripts in this
 * directory read TypeScript with regular expressions, which is fine for `id:"chess"` and
 * hopeless for two hundred path commands, so this one compiles instead: `typescript` is
 * already a devDependency of the repository, and registering a `.ts` handler on `require`
 * is enough to load the half-dozen modules involved with their own imports resolving normally.
 * It is deliberately the *whole* of the machinery — no watcher, no cache, no configuration
 * — and it runs on any Node this repository supports rather than on the versions that
 * happen to strip types natively.
 *
 * ## What it writes
 *
 * The images, and one manifest listing exactly the files it wrote. The manifest is what the
 * page metadata reads, so the metadata cannot name a file this script did not produce —
 * that is the rename this repository keeps getting bitten by, closed at the source rather
 * than described in a comment. `scripts/check-share-images.mjs` then checks the same claim
 * against the real export, because a manifest and a build can still disagree.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const require_ = createRequire(import.meta.url);

/**
 * Load `.ts` the way Node loads `.js`.
 *
 * `transpileModule` is the file-at-a-time compiler — no type checking, no project, no
 * program — which is exactly right here: `pnpm typecheck` already types these files, and
 * doing it twice would make the build slower for no more certainty. Registering the
 * extension is also what makes the extensionless imports inside them resolve, because
 * CommonJS resolution tries every extension it has a handler for.
 */
const ts = require_('typescript');
require_.extensions['.ts'] = (module, filename) => {
  const { outputText } = ts.transpileModule(readFileSync(filename, 'utf8'), {
    fileName: filename,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  module._compile(outputText, filename);
};

const { CARD_HEIGHT, CARD_WIDTH, renderDefaultCard, renderGameCard } = require_(
  join(ROOT, 'apps/web/src/lib/share/card.ts'),
);
const { CATALOGUE } = require_(join(ROOT, 'apps/web/src/data/catalogue.generated.ts'));

const OUT_DIR = join(ROOT, 'apps/web/public/og');
const MANIFEST = join(ROOT, 'apps/web/src/data/share-images.generated.ts');

/** The card every route that is not one game's page points at. */
const DEFAULT_FILE = 'duelbox.png';

/**
 * Emptied rather than written over.
 *
 * A renamed game leaves its old card behind otherwise, and a stale card is worse than a
 * missing one: nothing fails, and the site keeps serving a preview for a game it no longer
 * has. `check-share-images.mjs` fails on an unreferenced file for the same reason, so the
 * two agree about what the directory is allowed to contain.
 */
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const started = Date.now();
const written = [];
let bytes = 0;
let largest = 0;

function emit(name, png) {
  writeFileSync(join(OUT_DIR, name), png);
  written.push(name);
  bytes += png.length;
  largest = Math.max(largest, png.length);
}

emit(DEFAULT_FILE, renderDefaultCard(CATALOGUE));
for (const game of CATALOGUE) emit(`${game.slug}.png`, renderGameCard(game));

const files = [...written].sort();
const listed = files.map((file) => `  '${file}',`).join('\n');
writeFileSync(
  MANIFEST,
  `// Generated by scripts/generate-share-images.mjs. Do not edit by hand — run \`pnpm share:images\`.
//
// This is the list of files that script actually wrote, which is the point of it: the page
// metadata reads this rather than composing a URL out of a slug, so a change to how the
// cards are named cannot leave the metadata pointing at the old name.

/** The frame every card is composed in, and the size the metadata declares to a platform. */
export const SHARE_IMAGE_WIDTH = ${String(CARD_WIDTH)};
export const SHARE_IMAGE_HEIGHT = ${String(CARD_HEIGHT)};

/** Where the cards sit in the export, as a site-relative directory. */
export const SHARE_IMAGE_DIR = '/og';

/** The card for every route that is not one game's page. */
export const DEFAULT_SHARE_IMAGE_FILE = '${DEFAULT_FILE}';

/** Every file in that directory, as written. */
export const SHARE_IMAGE_FILES: readonly string[] = [
${listed}
];
`,
);

const seconds = ((Date.now() - started) / 1000).toFixed(1);
console.log(
  `generate-share-images: ${String(written.length)} card(s), ` +
    `${String(Math.round(bytes / 1024))} kB total, ${seconds}s → ${relative(ROOT, OUT_DIR)}`,
);
console.log(
  `generate-share-images: largest ${String(Math.round(largest / 1024))} kB,` +
    ` manifest → ${relative(ROOT, MANIFEST)}`,
);
