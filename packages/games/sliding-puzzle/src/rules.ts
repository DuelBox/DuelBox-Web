/* The shuffle, and why it is not a shuffle                                     */
/* -------------------------------------------------------------------------- */

/**
 * How many legal slides the generator plays away from the finished board.
 *
 * Long enough that the walk reaches the middle ground between the two goals — the two
 * finished boards are twenty taxicab units apart, so a position equidistant from both is
 * at least ten from each — and short enough that the acceptance test below is met inside
 * a handful of attempts. Measured; the numbers are in SPEC.md.
 */
export const SHUFFLE_WALK = 22;

/**
 * How many walks to try before settling for the best one seen.
 *
 * Bounded because this runs in `init` on whatever seed the shell hands over, and an
 * unbounded search for a perfectly balanced start is a hang waiting for an unlucky seed.
 * About one walk in twenty is accepted, so 200 leaves a three-in-a-hundred-thousand chance
 * of falling back to the best walk seen; over 20000 seeds the fallback has never been
 * taken, and the tests assert it. Two hundred walks of twenty-two slides is 4400 array
 * writes, once, in `init`.
 */
export const SHUFFLE_ATTEMPTS = 200;

const walkBoard: number[] = new Array<number>(CELL_COUNT).fill(GAP);
const bestBoard: number[] = new Array<number>(CELL_COUNT).fill(GAP);
const walkMoves: number[] = new Array<number>(DIRECTION_COUNT).fill(0);

/**
 * How unbalanced a candidate start is. Zero is a start the two seats are equally placed
 * in: the same number of tiles home and the same total distance to go.
 *
 * Distance is weighted above tiles home because it is the finer measure — two positions
 * can agree on tiles home and be four moves apart in real progress.
 */
function imbalanceOf(board: readonly number[]): number {
  const p1Home = homeCount(board, 'p1');
  const p2Home = homeCount(board, 'p2');
  const p1Distance = homeDistance(board, 'p1');
  const p2Distance = homeDistance(board, 'p2');
  return Math.abs(p1Distance - p2Distance) * 4 + Math.abs(p1Home - p2Home);
}

/**
 * A start position, generated by **playing legal slides from the finished board** rather
 * than by permuting tiles.
 *
 * This is not a stylistic choice. Exactly half of the 9! arrangements of a 3x3 sliding
 * puzzle cannot be reached from the finished board by any sequence of slides, so a
 * shuffle that permutes tiles ships a puzzle that is impossible one time in two. A walk
 * of legal moves can only ever land inside the reachable half, and the test proves it by
 * enumerating that half — all 181440 of it — and checking every generated board is a
 * member.
 *
 * The walk never immediately retraces its own step, for the same reason the game bans a
 * takeback: a walk that may undo itself spends much of its length standing still.
 *
 * Two more things happen here, both about fairness rather than solvability:
 *
 * - **Attempts are rejected until the two seats start level**, on tiles home and on
 *   distance to go alike. The walk starts at *seat one's* finished board, so an
 *   unfiltered walk hands seat one a head start that no bot tuning could undo.
 * - **A seeded coin decides whether to turn the result half way round.** Rotating maps
 *   the accepted set onto itself and swaps the two seats' positions exactly, so the
 *   distribution this returns is invariant under the half-turn — the two seats are not
 *   merely level on two summary numbers, they face the same distribution of boards.
 */
export function shuffleInto(board: number[], rng: Rng): void {
  let bestImbalance = Number.POSITIVE_INFINITY;

  for (let attempt = 0; attempt < SHUFFLE_ATTEMPTS; attempt += 1) {
    solvedInto(walkBoard);
    let gap = CELL_COUNT - 1;
    let last = -1;
    for (let step = 0; step < SHUFFLE_WALK; step += 1) {
      const count = legalMovesInto(gap, last, walkMoves);
      const direction = walkMoves[rng.int(0, count)] ?? UP;
      const from = stepCell(gap, direction);
      if (from < 0) continue;
      walkBoard[gap] = valueAt(walkBoard, from);
      walkBoard[from] = GAP;
      gap = from;
      last = direction;
    }

    const imbalance = imbalanceOf(walkBoard);
    if (imbalance < bestImbalance) {
      bestImbalance = imbalance;
      for (let cell = 0; cell < CELL_COUNT; cell += 1) bestBoard[cell] = valueAt(walkBoard, cell);
    }
    if (bestImbalance === 0) break;
  }

  for (let cell = 0; cell < CELL_COUNT; cell += 1) board[cell] = valueAt(bestBoard, cell);
  if (rng.bool()) rotateBoard(board);
}

/** Where the gap ended up. */
export function gapOf(board: readonly number[]): number {
  for (let cell = 0; cell < CELL_COUNT; cell += 1) {
    if (valueAt(board, cell) === GAP) return cell;
  }
  return CELL_COUNT - 1;
}

/**
 * Deal a fresh match.
 *
 * `openingSeat` comes from the shell, which alternates it across the rounds of a best-of
 * so that first-mover advantage washes out. A game that assumed `p1` would hand the
 * opener's edge to the same person every round.
 */
export function resetMatch(match: Match, rng: Rng, openingSeat: SeatId): void {
  shuffleInto(match.board, rng);
  match.gap = gapOf(match.board);
  match.lastDirection = -1;
  match.active = openingSeat;
  // The opening turn is a single slide, and the closing turn falls out to a single one
  // too: that is what makes the two seats reply to each other the same number of times.
  match.turnSlides = 1;
  match.p1Moves = MOVES_PER_SEAT;
  match.p2Moves = MOVES_PER_SEAT;
  match.p1Best = homeCount(match.board, 'p1');
  match.p2Best = homeCount(match.board, 'p2');
  match.p1Closest = homeDistance(match.board, 'p1');
  match.p2Closest = homeDistance(match.board, 'p2');
  match.winner = null;
  match.movedValue = GAP;
  match.movedFrom = -1;
  match.movedTo = -1;
}

