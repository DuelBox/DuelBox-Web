export type BotDifficulty = 'easy' | 'normal' | 'hard';

/**
 * How many slides each tier looks ahead.
 *
 * Difficulty is only ever how far the bot sees and how often it throws the position away.
 * No tier reads anything a player sitting at the board cannot read, none gets an extra
 * slide, and none of them knows the solution — the evaluation below is the win condition
 * written out, and a player can count tiles home just as well.
 *
 * **Every depth is even, and that is load-bearing.** A turn is two slides, so an odd depth
 * stops half way through somebody's turn and values a position in which one seat still has
 * a slide in hand. Depth three gave `normal` a 56.4% opening-seat win rate; depth four,
 * one ply deeper and ending on the turn boundary, brought it to 51.3% with everything else
 * untouched. The horizon has to line up with the turn or the search is answering a
 * different question from the one the match asks.
 */
export const SEARCH_DEPTH: Readonly<Record<BotDifficulty, number>> = Object.freeze({
  easy: 2,
  normal: 4,
  hard: 6,
});

/** How often a tier abandons its search and slides a uniformly random legal tile. */
export const BLUNDER_CHANCE: Readonly<Record<BotDifficulty, number>> = Object.freeze({
  easy: 0.45,
  normal: 0.15,
  hard: 0,
});

/**
 * Values a bot draws from its generator per move, whatever it decides to do.
 *
 * Constant on purpose. Both draws happen before anything branches, so the generator
 * advances by the same amount whether the bot blunders or searches — a conditional draw
 * couples one seat's stream to how its opponent happens to be playing.
 */
export const BOT_DRAWS_PER_MOVE = 2;

/**
 * Filling the board wins outright, so it must outrank every position that has not.
 * Reduced by the ply so a solve two moves away is preferred to the same solve four away.
 */
const WIN_SCORE = 1_000_000;
const SCORE_FLOOR = -(WIN_SCORE + 1);

/**
 * The evaluation, written as weights, is **the win condition and nothing else**.
 *
 * Best arrangement first, closest approach as the tiebreak, exactly as {@link judge}
 * compares them — the weights are only chosen so that no amount of the lower term can
 * ever outweigh one unit of the higher one. Eight tiles are at most 32 units from home,
 * so a closest-approach term of +/-32 x 128 = +/-4096 cannot reach one banked tile at
 * 8192, and the live-position term of at most +/-64 cannot reach one unit of closest
 * approach at 128.
 *
 * The live term is not part of the win condition and is deliberately the smallest: a
 * depth-limited search that could not see past its horizon to a banked improvement would
 * otherwise find every move identical and pick the first. It orders positions the win
 * condition genuinely cannot tell apart, and never overrules it.
 */
export const BEST_WEIGHT = 8192;
export const CLOSEST_WEIGHT = 128;
export const LIVE_HOME_WEIGHT = 4;

