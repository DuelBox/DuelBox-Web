/**
 * The rules of a two-seat sliding puzzle, with nothing else in them.
 *
 * No rendering, no timing, no DOM: the game, the bot and the balance harness all read the
 * board through these functions, so there is exactly one definition of what a legal slide
 * is and of who has won.
 *
 * ## What makes a sliding puzzle a duel
 *
 * One board, one gap, alternating slides — and **two goals that are the same goal seen
 * from two chairs**. Seat one wants the tiles in reading order from where seat one sits;
 * seat two wants them in reading order from where seat two sits. Those two arrangements
 * are each other's half-turn, which is exactly the half-turn the shell already makes when
 * the board changes hands. So the seat rotation stops being decoration and becomes the
 * rule: every slide that carries a tile towards one player's order carries it away from
 * the other's, and neither player is solving a different puzzle from the one in front of
 * them.
 *
 * Two facts make that fair rather than merely symmetric, and both are proved in the tests:
 *
 * 1. **Both goals live in the same orbit.** Half of all permutations of a sliding puzzle
 *    cannot be reached from the solved board at all, so "the other player's goal" could
 *    easily have been unreachable. On a 3x3 it is reachable — the half-turn is an even
 *    permutation and moves the gap an even taxicab distance — and the board is only ever
 *    generated by *playing legal moves*, so every position we ship is solvable to both
 *    goals by construction.
 * 2. **The rules are invariant under the half-turn.** Rotating a position 180 degrees
 *    swaps the two seats' scores exactly and maps legal moves onto legal moves, so a
 *    match and its mirror are the same match with the chairs swapped. The shuffle flips a
 *    seeded coin and rotates, which makes the *distribution* of starting positions
 *    invariant too — there is no residual seat bias left for tuning to hide.
 */

/** Cells on a side. Three, and the reasoning for that is in SPEC.md. */
export const SIZE = 3;
export const CELL_COUNT = SIZE * SIZE;
/** Numbered tiles. The odd one out is the gap. */
export const TILE_COUNT = CELL_COUNT - 1;
/** The empty square, as a board value. Tiles are 1..TILE_COUNT. */
export const GAP = 0;

/**
 * How many slides each seat gets. The match ends when both budgets are spent, and nothing
 * that happens on the board can add one — which is the whole of this game's termination
 * argument. `roundSeconds` ends nothing anywhere in this repository.
 */
export const MOVES_PER_SEAT = 23;

/**
 * Slides in a turn — and the single most important number in this game.
 *
 * **One slide a turn is unplayable, and the measurement is not close.** Under strict
 * alternation the seat that *replies* won 99.7% at `hard`, 95.9% at `normal` and 77.8% at
 * `easy` over 600 matches a tier. Two uniformly random seats split 50/50 on the same
 * boards, so it is neither the shuffle nor the seats: the better both sides play, the worse
 * it is to be the one who has to commit first. Every slide gains something, and the replier
 * takes the larger half of every exchange, twenty-three exchanges running.
 *
 * Ending the match on the opener's slide instead of the replier's changed it by 0.1 of a
 * point, so it was never about the last word. It was about who answers whom.
 *
 * Turns of two slides, with the opening turn and the closing turn cut to one, hand the
 * reply back and forth: the order runs A, BB, AA, BB, ..., AA, B — the same order read
 * backwards with the chairs swapped, which is asserted in the tests. Each seat still makes
 * {@link MOVES_PER_SEAT} slides, and the opening seat's share falls from 99.7% to 48-52%.
 *
 * A Thue-Morse order — the textbook answer to exactly this problem — was tried too and came
 * out slightly worse (55-56%) as well as being impossible to explain to a player.
 */
export const SLIDES_PER_TURN = 2;

/** Directions the *gap* travels. A key or a tap names the tile on that side of it. */
export const UP = 0;
export const RIGHT = 1;
export const DOWN = 2;
export const LEFT = 3;
export const DIRECTION_COUNT = 4;

/** Up and down, left and right: two bits, so the reverse of a direction is one xor. */
export function opposite(direction: number): number {
  return direction ^ 2;
}

/** Cell the gap reaches by moving one step, or -1 when that runs off the board. */
export function stepCell(cell: number, direction: number): number {
  if (cell < 0 || cell >= CELL_COUNT) return -1;
  const row = Math.floor(cell / SIZE);
  const column = cell % SIZE;
  switch (direction) {
    case UP:
      return row === 0 ? -1 : cell - SIZE;
    case RIGHT:
      return column === SIZE - 1 ? -1 : cell + 1;
    case DOWN:
      return row === SIZE - 1 ? -1 : cell + SIZE;
    case LEFT:
      return column === 0 ? -1 : cell - 1;
    default:
      return -1;
  }
}

/** The half-turn on cells. Its own inverse, which is why one function serves both seats. */
export function rotateCell(cell: number): number {
  return CELL_COUNT - 1 - cell;
}

/**
 * Where a tile belongs, for one seat.
 *
 * Seat one reads the board from the top left, so tile `v` belongs in cell `v - 1`. Seat
 * two reads the same board from the other side, so their home cell is the half-turn of
 * seat one's: `rotateCell(v - 1)`, which is `CELL_COUNT - v`.
 *
 * On an odd board the centre is its own half-turn, so tile 5 has the same home for both
 * players. That single shared cell is the only cooperative square on the board.
 */
export function homeCellFor(seat: SeatId, value: number): number {
  return seat === 'p1' ? value - 1 : CELL_COUNT - value;
}

/** Taxicab distance between two cells, in cells. */
export function cellDistance(a: number, b: number): number {
  const rows = Math.floor(a / SIZE) - Math.floor(b / SIZE);
  const columns = (a % SIZE) - (b % SIZE);
  return Math.abs(rows) + Math.abs(columns);
}

/**
 * The live board and the state that decides a match.
 *
 * Flat and mutable on purpose: a match is stepped inside a fixed timestep that may not
 * allocate, and the balance harness plays thousands of them.
 */
export interface Match {
  /** Cell `c` holds a tile value in 1..TILE_COUNT, or {@link GAP}. */
  readonly board: number[];
  /** Cell the gap is in. Derived from `board`, kept alongside so a move is O(1). */
  gap: number;
  /** Direction the gap moved on the last slide, or -1 before the first one. */
  lastDirection: number;
  active: SeatId;
  /** Slides left in the active seat's turn. One on the opening turn, two after it. */
  turnSlides: number;
  /** Slides each seat has left. */
  p1Moves: number;
  p2Moves: number;
  /**
   * The most tiles this seat has ever had standing in its own order at once, and the
   * closest its whole board has ever come to that order. Both are best-ever marks that
   * only ever improve — see {@link bank} for why the score cannot be a reading of the
   * final position.
   */
  p1Best: number;
  p2Best: number;
  p1Closest: number;
  p2Closest: number;
  winner: SeatId | 'draw' | null;
  /** The tile the last slide moved, and where it came from and went. For the renderer. */
  movedValue: number;
  movedFrom: number;
  movedTo: number;
}

export function createMatch(): Match {
  const board: number[] = [];
  for (let i = 0; i < CELL_COUNT; i += 1) board.push(GAP);
  return {
    board,
    gap: CELL_COUNT - 1,
    lastDirection: -1,
    active: 'p1',
    turnSlides: 1,
    p1Moves: MOVES_PER_SEAT,
    p2Moves: MOVES_PER_SEAT,
    p1Best: 0,
    p2Best: 0,
    p1Closest: 0,
    p2Closest: 0,
    winner: null,
    movedValue: GAP,
    movedFrom: -1,
    movedTo: -1,
  };
}

/** Reads through `noUncheckedIndexedAccess`; an out-of-range cell reads as the gap. */
function valueAt(board: readonly number[], cell: number): number {
  return board[cell] ?? GAP;
}

/** Seat one's finished board: 1..8 in reading order with the gap in the last cell. */
export function solvedInto(board: number[]): void {
  for (let cell = 0; cell < CELL_COUNT - 1; cell += 1) board[cell] = cell + 1;
  board[CELL_COUNT - 1] = GAP;
}

/** Turn a board half way round in place. The involution the whole game is built on. */
export function rotateBoard(board: number[]): void {
  for (let cell = 0; cell < Math.floor(CELL_COUNT / 2); cell += 1) {
    const far = rotateCell(cell);
    const held = valueAt(board, cell);
    board[cell] = valueAt(board, far);
    board[far] = held;
  }
}

/** Tiles standing in their home cell for `seat`, right now. */
export function homeCount(board: readonly number[], seat: SeatId): number {
  let count = 0;
  for (let cell = 0; cell < CELL_COUNT; cell += 1) {
    const value = valueAt(board, cell);
    if (value === GAP) continue;
    if (homeCellFor(seat, value) === cell) count += 1;
  }
  return count;
}

/**
 * How far every tile is from where `seat` wants it, summed. The tiebreak, and the only
 * measure that moves on every single slide.
 */
export function homeDistance(board: readonly number[], seat: SeatId): number {
  let total = 0;
  for (let cell = 0; cell < CELL_COUNT; cell += 1) {
    const value = valueAt(board, cell);
    if (value === GAP) continue;
    total += cellDistance(cell, homeCellFor(seat, value));
  }
  return total;
}

/**
 * The legal slides in a position, written into `out` from `offset`, and how many there are.
 *
 * Two rules, and the second is the one that makes the game a game. A slide is legal when
 * the gap can travel that way, and when it is **not the exact reverse of the slide just
 * played**: without that, every move a player makes is undone by the reply, and two seats
 * pushing towards opposite goals simply oscillate for the whole match.
 *
 * The gap always has at least two neighbours on a board this size, so banning one reverse
 * can never leave a player with nothing to do. There is no pass rule because there cannot
 * be a position that needs one.
 */
export function legalMovesInto(
  gap: number,
  lastDirection: number,
  out: number[],
  offset = 0,
): number {
  const banned = lastDirection < 0 ? -1 : opposite(lastDirection);
  let count = 0;
  for (let direction = 0; direction < DIRECTION_COUNT; direction += 1) {
    if (direction === banned) continue;
    if (stepCell(gap, direction) < 0) continue;
    out[offset + count] = direction;
    count += 1;
  }
  return count;
}

/** Whether `direction` is a slide this position allows. */
export function isLegalMove(match: Readonly<Match>, direction: number): boolean {
  if (direction < 0 || direction >= DIRECTION_COUNT) return false;
  if (match.winner !== null) return false;
  if (match.lastDirection >= 0 && direction === opposite(match.lastDirection)) return false;
  return stepCell(match.gap, direction) >= 0;
}

/** How many slides `seat` has left. */
export function movesLeft(match: Readonly<Match>, seat: SeatId): number {
  return seat === 'p1' ? match.p1Moves : match.p2Moves;
}

/** Slides the seat taking over would get. The tail of a budget shortens the last turn. */
function turnLengthFor(remaining: number): number {
  return remaining < SLIDES_PER_TURN ? remaining : SLIDES_PER_TURN;
}

/**
 * Take the best-ever marks up to what the board shows now.
 *
 * **The score is a high-water mark rather than a reading of the final board.** Scoring the
 * final position is the obvious rule and it is the wrong one here: a player who spends
 * twenty slides building an arrangement can have it taken apart by the opponent's last
 * slide, so what the match measures is who moved most recently rather than who played best.
 *
 * On its own this did not fix the reply advantage — see {@link SLIDES_PER_TURN}, which is
 * what did — and it is worth being exact about that rather than claiming both. Under strict
 * alternation, final-position scoring gave the replying seat 99.9% at `hard`, 90.1% at
 * `normal` and 73.2% at `easy`; banking the best moved those to 99.7%, 95.9% and 77.8%,
 * which is to say it moved nothing. It earns its place for the other reason.
 *
 * It is the more honest rule for this puzzle. "The neatest arrangement you managed" is what
 * a person playing a sliding puzzle is proud of, and being one tile from a finished board
 * when the slides run out is not less of an achievement because the other player nudged a
 * tile afterwards. It also gives the shell a score that only ever climbs.
 */
export function bank(match: Match): void {
  const p1Home = homeCount(match.board, 'p1');
  const p2Home = homeCount(match.board, 'p2');
  if (p1Home > match.p1Best) match.p1Best = p1Home;
  if (p2Home > match.p2Best) match.p2Best = p2Home;
  const p1Distance = homeDistance(match.board, 'p1');
  const p2Distance = homeDistance(match.board, 'p2');
  if (p1Distance < match.p1Closest) match.p1Closest = p1Distance;
  if (p2Distance < match.p2Closest) match.p2Closest = p2Distance;
}

const CONDITION: WinCondition = { kind: 'highest-when-time-expires' };
/** Reused so judging a position allocates nothing; a match is judged after every slide. */
const tally = { p1: 0, p2: 0 };
const timeExpired = { timeExpired: true };

/**
 * Decide the match, or null while it is still running.
 *
 * Filling the board in your own order wins on the spot — that is what a sliding puzzle
 * means, and the two orders are exclusive everywhere but the centre, so both seats can
 * never claim it at once. Otherwise the seat whose best arrangement held more tiles takes
 * it, and a tie there goes to whoever came closest to their own order.
 *
 * The closest-approach tiebreak is not decoration. A best arrangement is an integer
 * between nought and eight and two players of the same standard land on the same one of
 * those nine values often; the measured draw rates with and without it are in SPEC.md.
 */
export function judge(match: Readonly<Match>): SeatId | 'draw' | null {
  if (homeCount(match.board, 'p1') === TILE_COUNT) return 'p1';
  if (homeCount(match.board, 'p2') === TILE_COUNT) return 'p2';
  if (match.p1Moves > 0 || match.p2Moves > 0) return null;

  tally.p1 = match.p1Best;
  tally.p2 = match.p2Best;
  const outcome = resolve(CONDITION, tally, timeExpired);
  if (outcome !== 'draw') return outcome;
  if (match.p1Closest === match.p2Closest) return 'draw';
  return match.p1Closest < match.p2Closest ? 'p1' : 'p2';
}

export function winnerOf(match: Readonly<Match>): SeatId | 'draw' | null {
  return match.winner;
}

/**
 * Play a slide. Returns false and changes nothing when it is not one this position allows,
 * so a caller may offer any tap or key at all.
 */
export function applyMove(match: Match, direction: number): boolean {
  if (!isLegalMove(match, direction)) return false;
  const from = stepCell(match.gap, direction);
  if (from < 0) return false;

  const value = valueAt(match.board, from);
  match.board[match.gap] = value;
  match.board[from] = GAP;
  match.movedValue = value;
  match.movedFrom = from;
  match.movedTo = match.gap;
  match.gap = from;
  match.lastDirection = direction;

  if (match.active === 'p1') match.p1Moves -= 1;
  else match.p2Moves -= 1;
  match.turnSlides -= 1;

  // Both seats' marks are taken from every position, whoever produced it: the board is
  // shared, so an arrangement is an arrangement however it came about.
  bank(match);
  match.winner = judge(match);
  if (match.winner !== null) return true;

  if (match.turnSlides <= 0 || movesLeft(match, match.active) === 0) {
    const next = otherSeat(match.active);
    match.active = next;
    match.turnSlides = turnLengthFor(movesLeft(match, next));
  }
  return true;
}

