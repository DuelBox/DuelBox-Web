let searchP1Moves = 0;
let searchP2Moves = 0;
let searchTurnSlides = 1;
let searchSeat: SeatId = 'p1';
/** The banked marks carried down the tree, saved and restored around every slide. */
let searchP1Best = 0;
let searchP2Best = 0;
let searchP1Closest = 0;
let searchP2Closest = 0;

/** One slot per direction per ply, so generating moves at a node allocates nothing. */
const MAX_DEPTH = 10;
const moveStack: number[] = new Array<number>((MAX_DEPTH + 2) * DIRECTION_COUNT).fill(0);
/** Scratch for the blunder draw. */
const blunderMoves: number[] = new Array<number>(DIRECTION_COUNT).fill(0);

/** Filled by {@link measure}; read by the evaluation without walking the board twice. */
let measuredP1Home = 0;
let measuredP2Home = 0;
let measuredP1Distance = 0;
let measuredP2Distance = 0;

function measure(board: readonly number[]): void {
  let p1Home = 0;
  let p2Home = 0;
  let p1Distance = 0;
  let p2Distance = 0;
  for (let cell = 0; cell < CELL_COUNT; cell += 1) {
    const value = valueAt(board, cell);
    if (value === GAP) continue;
    const p1Cell = value - 1;
    const p2Cell = CELL_COUNT - value;
    if (p1Cell === cell) p1Home += 1;
    if (p2Cell === cell) p2Home += 1;
    p1Distance += cellDistance(cell, p1Cell);
    p2Distance += cellDistance(cell, p2Cell);
  }
  measuredP1Home = p1Home;
  measuredP2Home = p2Home;
  measuredP1Distance = p1Distance;
  measuredP2Distance = p2Distance;
}

/**
 * The banked marks, plus the last {@link measure}, read as a score for `seat`.
 *
 * Exactly antisymmetric — `staticScore('p1') === -staticScore('p2')` — which is what lets
 * the search be a plain negamax with no side-to-move corrections anywhere in it.
 */
function staticScore(seat: SeatId): number {
  const forP1 =
    BEST_WEIGHT * (searchP1Best - searchP2Best) +
    CLOSEST_WEIGHT * (searchP2Closest - searchP1Closest) +
    LIVE_HOME_WEIGHT * (measuredP1Home - measuredP2Home) +
    (measuredP2Distance - measuredP1Distance);
  return seat === 'p1' ? forP1 : -forP1;
}

/** Take the search's banked marks up to the position {@link measure} just read. */
function bankSearch(): void {
  if (measuredP1Home > searchP1Best) searchP1Best = measuredP1Home;
  if (measuredP2Home > searchP2Best) searchP2Best = measuredP2Home;
  if (measuredP1Distance < searchP1Closest) searchP1Closest = measuredP1Distance;
  if (measuredP2Distance < searchP2Closest) searchP2Closest = measuredP2Distance;
}

function searchMovesLeft(seat: SeatId): number {
  return seat === 'p1' ? searchP1Moves : searchP2Moves;
}

function spendSearchMove(seat: SeatId, delta: number): void {
  if (seat === 'p1') searchP1Moves += delta;
  else searchP2Moves += delta;
}

/**
 * Who slides next once `toMove` has just slid, updating the turn counter to match.
 *
 * The same seat continues while its turn has slides left, which is the whole reason this
 * exists: a search that assumed strict alternation would plan the first half of every
 * two-slide turn and hand the second one to the opponent in its head.
 */
function advanceSearchTurn(toMove: SeatId): SeatId {
  if (searchTurnSlides > 0 && searchMovesLeft(toMove) > 0) return toMove;
  const next = otherSeat(toMove);
  searchTurnSlides = turnLengthFor(searchMovesLeft(next));
  return next;
}

/** Slide on {@link searchBoard}. Returns the direction to restore on the way back up. */
function doSearchMove(direction: number): number {
  const from = stepCell(searchGap, direction);
  searchBoard[searchGap] = valueAt(searchBoard, from);
  searchBoard[from] = GAP;
  searchGap = from;
  const previous = searchLast;
  searchLast = direction;
  return previous;
}

function undoSearchMove(direction: number, previousLast: number): void {
  const back = stepCell(searchGap, opposite(direction));
  searchBoard[searchGap] = valueAt(searchBoard, back);
  searchBoard[back] = GAP;
  searchGap = back;
  searchLast = previousLast;
}

/**
 * Negamax with an alpha-beta window, scored from the point of view of `toMove`.
 *
 * The window only ever prunes branches whose value cannot change the choice made above
 * them, so the answer is the one an exhaustive search of the same depth gives.
 */
function search(
  toMove: SeatId,
  depth: number,
  ply: number,
  alpha: number,
  beta: number,
  budget: SearchBudget,
): number {
  // Charged on every node, leaves included: leaves are the overwhelming majority of the
  // work, and charging only internal nodes puts the ceiling above the thing it limits.
  const funded = budget.spend();
  measure(searchBoard);
  if (measuredP1Home === TILE_COUNT) {
    return toMove === 'p1' ? WIN_SCORE - ply : ply - WIN_SCORE;
  }
  if (measuredP2Home === TILE_COUNT) {
    return toMove === 'p2' ? WIN_SCORE - ply : ply - WIN_SCORE;
  }
  if (searchP1Moves === 0 && searchP2Moves === 0) return staticScore(toMove);
  if (!funded || depth <= 0) return staticScore(toMove);

  const base = ply * DIRECTION_COUNT;
  const count = legalMovesInto(searchGap, searchLast, moveStack, base);
  let best = SCORE_FLOOR;
  let lower = alpha;

  for (let i = 0; i < count; i += 1) {
    const direction = moveStack[base + i] ?? UP;
    const previousLast = doSearchMove(direction);
    const heldP1Best = searchP1Best;
    const heldP2Best = searchP2Best;
    const heldP1Closest = searchP1Closest;
    const heldP2Closest = searchP2Closest;
    const heldTurn = searchTurnSlides;
    measure(searchBoard);
    bankSearch();
    spendSearchMove(toMove, -1);
    searchTurnSlides -= 1;
    const next = advanceSearchTurn(toMove);
    // Negated only when the move passes to the other seat. A seat continuing its own turn
    // keeps the window and the sign, which is what makes a two-slide turn one plan.
    const score =
      next === toMove
        ? search(toMove, depth - 1, ply + 1, lower, beta, budget)
        : -search(next, depth - 1, ply + 1, -beta, -lower, budget);
    searchTurnSlides = heldTurn;
    spendSearchMove(toMove, 1);
    searchP1Best = heldP1Best;
    searchP2Best = heldP2Best;
    searchP1Closest = heldP1Closest;
    searchP2Closest = heldP2Closest;
    undoSearchMove(direction, previousLast);

    if (score > best) best = score;
    if (best > lower) lower = best;
    if (lower >= beta) break;
  }
  return best;
}

/**
 * The budget and the sweep are module-level so that a bot's move costs no allocation at
 * all, not even the closure `deepen` is handed.
 */
const searchBudget = new SearchBudget(DEFAULT_SEARCH_NODES);

/** One full sweep at a fixed depth, or null when the budget ran out part-way through. */
const sweep = (depth: number): number | null => {
  const count = legalMovesInto(searchGap, searchLast, moveStack, 0);
  const rootTurn = searchTurnSlides;
  let bestDirection = -1;
  let bestScore = SCORE_FLOOR;

  for (let i = 0; i < count; i += 1) {
    const direction = moveStack[i] ?? UP;
    const previousLast = doSearchMove(direction);
    const heldP1Best = searchP1Best;
    const heldP2Best = searchP2Best;
    const heldP1Closest = searchP1Closest;
    const heldP2Closest = searchP2Closest;
    measure(searchBoard);
    bankSearch();
    spendSearchMove(searchSeat, -1);
    searchTurnSlides -= 1;
    const next = advanceSearchTurn(searchSeat);
    const score =
      next === searchSeat
        ? search(searchSeat, depth - 1, 1, bestScore, Infinity, searchBudget)
        : -search(next, depth - 1, 1, -Infinity, -bestScore, searchBudget);
    searchTurnSlides = rootTurn;
    spendSearchMove(searchSeat, 1);
    searchP1Best = heldP1Best;
    searchP2Best = heldP2Best;
    searchP1Closest = heldP1Closest;
    searchP2Closest = heldP2Closest;
    undoSearchMove(direction, previousLast);

    if (searchBudget.exhausted) return null;
    if (bestDirection < 0 || score > bestScore) {
      bestScore = score;
      bestDirection = direction;
    }
  }
  return bestDirection;
};

/** Nodes the last {@link botMove} spent. For the cost tests and for SPEC.md. */
export function lastSearchNodes(): number {
  return searchBudget.spent;
}

/**
 * The slide `seat` should play, or -1 on a position with no legal slide — which this game
 * cannot produce, and which is answered rather than thrown so a caller never has to know.
 *
 * With the tier's blunder chance a uniformly random legal slide is played instead of the
 * searched one; otherwise the position is searched to the tier's depth under a
 * deterministic node budget, so the same board costs the same on a phone and on a laptop
 * and returns the same move. Ties break towards the lowest direction index, so the same
 * board and the same generator state always give the same slide.
 */
export function botMove(match: Readonly<Match>, rng: Rng, difficulty: BotDifficulty): number {
  const count = legalMovesInto(match.gap, match.lastDirection, blunderMoves);
  // Both draws happen here, unconditionally and before anything branches, so a seat's
  // stream advances by BOT_DRAWS_PER_MOVE however the move is decided.
  const blunder = rng.bool(BLUNDER_CHANCE[difficulty]);
  const ordinal = rng.int(0, count > 0 ? count : 1);
  searchBudget.reset();
  if (count === 0) return -1;
  if (blunder) return blunderMoves[ordinal] ?? -1;

  for (let cell = 0; cell < CELL_COUNT; cell += 1) searchBoard[cell] = valueAt(match.board, cell);
  searchGap = match.gap;
  searchLast = match.lastDirection;
  searchP1Moves = match.p1Moves;
  searchP2Moves = match.p2Moves;
  searchP1Best = match.p1Best;
  searchP2Best = match.p2Best;
  searchP1Closest = match.p1Closest;
  searchP2Closest = match.p2Closest;
  searchTurnSlides = match.turnSlides;
  searchSeat = match.active;

  const depth = Math.min(SEARCH_DEPTH[difficulty], MAX_DEPTH);
  const found = deepen(searchBudget, depth, sweep);
  return found >= 0 ? found : (blunderMoves[0] ?? -1);
}

/**
 * A generator per seat, derived once from the match seed.
 *
 * A shared stream is unbiased in a strict-alternation turn game *as long as* every turn
 * costs the same number of draws — and that is a property a later change breaks silently.
 * Two streams make the independence structural: seat two plays the identical slides
 * against `easy` and against `hard`, which is asserted in the tests.
 */
export function createBotRngs(rng: Rng): Readonly<Record<SeatId, Rng>> {
  return { p1: new Rng(rng.next() | 0), p2: new Rng(rng.next() | 0) };
}
